using AlgoPlatform.Oms;
using AlgoPlatform.Sdk;

namespace AlgoPlatform.Tests.Trading;

public class OmsTests
{
    private static readonly InstrumentId Vod = new(1);

    [Fact]
    public void Positions_track_average_price_and_realised_pnl()
    {
        var oms = new OrderManager(1);
        long b = oms.NextOrderId();
        oms.Create(b, new NewOrder(Vod, Side.Buy, OrdType.Limit, Tif.Day, 100, 10));
        oms.Apply(new ExecutionReport(0, b, 1, Vod, Side.Buy, OrdStatus.PartiallyFilled, 100, 4, 4, 6, 0));
        oms.Apply(new ExecutionReport(0, b, 2, Vod, Side.Buy, OrdStatus.Filled, 110, 6, 10, 0, 0));
        var p = oms.GetPosition(Vod);
        Assert.Equal(10, p.NetQty);
        Assert.Equal(106, p.AvgPx);   // (4*100 + 6*110) / 10

        long s = oms.NextOrderId();
        oms.Create(s, new NewOrder(Vod, Side.Sell, OrdType.Limit, Tif.Day, 120, 15));
        oms.Apply(new ExecutionReport(0, s, 3, Vod, Side.Sell, OrdStatus.Filled, 120, 15, 15, 0, 0));
        p = oms.GetPosition(Vod);
        Assert.Equal(-5, p.NetQty);
        Assert.Equal(120, p.AvgPx);                  // flipped short at 120
        Assert.Equal((120 - 106) * 10, p.RealisedPnl);
        Assert.Equal(0, oms.LiveOrderCount);
        Assert.Equal(0, oms.OrderCount);             // terminal orders are not retained by default
    }

    [Fact]
    public void Cancel_reject_restores_the_order_and_replace_ack_updates_it()
    {
        var oms = new OrderManager(1) { RetainTerminalOrders = true };
        long id = oms.NextOrderId();
        oms.Create(id, new NewOrder(Vod, Side.Buy, OrdType.Limit, Tif.Day, 100, 10));
        Assert.False(oms.CanReplace(id, 20, out _));   // not acknowledged yet
        oms.Apply(new ExecutionReport(0, id, 1, Vod, Side.Buy, OrdStatus.Working, 0, 0, 0, 10, 0));
        Assert.True(oms.RequestCancel(id));
        oms.TryGet(id, out var o);
        Assert.Equal(OrdStatus.PendingCancel, o.ExternalStatus);
        oms.Apply(new ExecutionReport(0, id, 0, Vod, Side.Buy, OrdStatus.Working, 0, 0, 0, 10, RejectCodes.ExchangeReject));
        oms.TryGet(id, out o);
        Assert.Equal(OrdStatus.Working, o.ExternalStatus);

        Assert.True(oms.CanReplace(id, 20, out _));
        oms.RequestReplace(id, 105, 20);
        Assert.Equal(20, oms.OpenBuyQty(Vod));   // conservative while pending
        oms.Apply(new ExecutionReport(0, id, 2, Vod, Side.Buy, OrdStatus.Working, 0, 0, 0, 20, 0));
        oms.TryGet(id, out o);
        Assert.Equal(105, o.Px);
        Assert.Equal(20, o.OrderQty);
        Assert.Equal(OrdStatus.Working, o.ExternalStatus);
    }

    /// <summary>
    /// Acceptance test 5: random sequences of acks, partial fills, cancels, replaces, rejects and duplicate
    /// reports, generated by a model exchange. After every step CumQty + LeavesQty = OrderQty for live
    /// orders, OMS state equals exchange state, and a duplicate ExecId never changes anything.
    /// </summary>
    [Fact]
    public void Property_random_report_sequences_keep_invariants()
    {
        for (int trial = 0; trial < 300; trial++) RunTrial(new Random(trial));
    }

    private sealed class ExOrder
    {
        public long Id;
        public long Qty;
        public long Cum;
        public bool Acked;
        public OrdStatus Status = OrdStatus.PendingNew;
        public bool Live => Status is OrdStatus.PendingNew or OrdStatus.Working or OrdStatus.PartiallyFilled;
        public long Leaves => Live ? Qty - Cum : 0;
    }

    private static void RunTrial(Random rng)
    {
        var oms = new OrderManager(1) { RetainTerminalOrders = true };
        var ex = new List<ExOrder>();
        var history = new List<ExecutionReport>();
        long execId = 0;
        long filledNet = 0;

        for (int i = 0; i < rng.Next(1, 6); i++)
        {
            long id = oms.NextOrderId();
            long qty = rng.Next(1, 20) * 50;
            oms.Create(id, new NewOrder(Vod, Side.Buy, OrdType.Limit, Tif.Day, 100, qty));
            ex.Add(new ExOrder { Id = id, Qty = qty });
        }

        void Send(ExOrder o, OrdStatus status, long lastQty, int reject = 0, bool withExecId = true)
        {
            var r = new ExecutionReport(0, o.Id, withExecId ? ++execId : 0, Vod, Side.Buy, status, lastQty > 0 ? 100 : 0, lastQty, o.Cum, o.Leaves, reject);
            history.Add(r);
            Assert.Equal(ApplyResult.Applied, oms.Apply(r));
        }

        for (int step = 0; step < 60; step++)
        {
            ExOrder o = ex[rng.Next(ex.Count)];
            switch (rng.Next(7))
            {
                case 0 when o.Status == OrdStatus.PendingNew:
                    o.Status = OrdStatus.Working;
                    o.Acked = true;
                    Send(o, OrdStatus.Working, 0);
                    break;
                case 1 when o.Status == OrdStatus.PendingNew && rng.Next(4) == 0:
                    o.Status = OrdStatus.Rejected;
                    Send(o, OrdStatus.Rejected, 0, RejectCodes.ExchangeReject);
                    break;
                case 2 when o.Live && o.Acked:
                {
                    long q = rng.Next(1, (int)o.Leaves + 1);
                    o.Cum += q;
                    filledNet += q;
                    o.Status = o.Cum == o.Qty ? OrdStatus.Filled : OrdStatus.PartiallyFilled;
                    Send(o, o.Status, q);
                    break;
                }
                case 3:
                    if (!oms.RequestCancel(o.Id)) break;
                    if (o.Live && o.Acked)
                    {
                        o.Status = OrdStatus.Cancelled;
                        Send(o, OrdStatus.Cancelled, 0);
                    }
                    else
                    {
                        // Exchange has not acked it yet, so it rejects the cancel; the order is unchanged.
                        Send(o, OrdStatus.Working, 0, RejectCodes.ExchangeReject, withExecId: false);
                    }
                    break;
                case 4:
                {
                    long newQty = o.Cum + rng.Next(1, 20) * 10;
                    if (!oms.CanReplace(o.Id, newQty, out _)) break;
                    oms.RequestReplace(o.Id, 101, newQty);
                    o.Qty = newQty;
                    Send(o, o.Cum > 0 ? OrdStatus.PartiallyFilled : OrdStatus.Working, 0);
                    break;
                }
                case 5 when history.Count > 0:
                {
                    // Duplicate: re-deliver an old report; nothing may change.
                    var dup = history[rng.Next(history.Count)];
                    if (dup.ExecId == 0) break;
                    var before = oms.Snapshot().OrderBy(s => s.OrderId).ToList();
                    var pos = oms.GetPosition(Vod);
                    Assert.NotEqual(ApplyResult.Applied, oms.Apply(dup));
                    Assert.Equal(before, oms.Snapshot().OrderBy(s => s.OrderId).ToList());
                    Assert.Equal(pos, oms.GetPosition(Vod));
                    break;
                }
            }

            Assert.Equal(0, oms.InvariantViolations);
            foreach (ExOrder e in ex)
            {
                Assert.True(oms.TryGet(e.Id, out OrderState s));
                if (s.IsLive) Assert.Equal(s.OrderQty, s.CumQty + s.LeavesQty);
                Assert.Equal(e.Cum, s.CumQty);
                if (e.Status != OrdStatus.PendingNew) Assert.Equal(e.Leaves, s.LeavesQty);
                Assert.Equal(e.Live, s.IsLive);
            }
            Assert.Equal(filledNet, oms.GetPosition(Vod).NetQty);
            Assert.Equal(ex.Sum(e => e.Live ? Math.Max(e.Leaves, 0) : 0), oms.OpenBuyQty(Vod));
        }
    }
}
